-- Migration 6 of 8: orders, their items and their history.
--
-- IMPORTANT: clients can only READ these tables. Every write goes through a function
-- (place_order, update_order_status, accept_delivery) so totals, fees and status changes cannot
-- be forged by a modified app. See the next two migrations.

-- ---------------------------------------------------------------------------------------------
-- orders
-- An order stores its own copy ("snapshot") of the delivery address, the recipient and the money,
-- so later edits to a profile, address, store or price never rewrite history. This is also what
-- lets a customer order for someone else: the recipient is whoever is written on the order.
-- ---------------------------------------------------------------------------------------------
create table public.orders (
  id bigint generated always as identity primary key,
  customer_id uuid not null references public.profiles (id) on delete restrict,
  store_id bigint not null references public.stores (id) on delete restrict,
  -- Empty until a rider accepts; the first rider to accept wins (see accept_delivery).
  rider_id uuid references public.riders (user_id) on delete restrict,
  status public.order_status not null default 'placed',
  -- Generated by the app once per checkout attempt, so a double tap or a network retry can never
  -- create two orders.
  idempotency_key uuid not null,
  payment_method public.payment_method not null default 'cod',

  store_name text not null,

  recipient_name text not null check (char_length(trim(recipient_name)) between 1 and 120),
  recipient_phone public.phone_number not null,
  address_line text not null check (char_length(trim(address_line)) between 1 and 300),
  area text check (char_length(area) <= 120),
  city text not null check (char_length(trim(city)) between 1 and 80),
  instructions text check (char_length(instructions) <= 300),
  latitude double precision not null check (latitude between -90 and 90),
  longitude double precision not null check (longitude between -180 and 180),
  location extensions.geography(point, 4326) generated always as (
    extensions.st_setsrid(extensions.st_makepoint(longitude, latitude), 4326)::extensions.geography
  ) stored,
  notes text check (char_length(notes) <= 500),

  -- Money (PKR). All computed by the database in place_order().
  subtotal numeric(12, 2) not null check (subtotal >= 0),
  -- Straight-line distance store -> address, kept so the fee can always be explained afterwards.
  distance_m integer not null check (distance_m >= 0),
  fee_per_km numeric(8, 2) not null check (fee_per_km >= 0),
  delivery_fee numeric(12, 2) not null check (delivery_fee >= 0),
  total numeric(12, 2) generated always as (subtotal + delivery_fee) stored,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  unique (customer_id, idempotency_key)
);

comment on table public.orders is
  'Customer orders. Read-only for clients; created and advanced only through database functions.';

-- "My orders", newest first.
create index orders_customer_created_idx on public.orders (customer_id, created_at desc);
-- The store's order list.
create index orders_store_created_idx on public.orders (store_id, created_at desc);
-- A rider's own deliveries.
create index orders_rider_created_idx on public.orders (rider_id, created_at desc) where rider_id is not null;
-- Deliveries waiting for a rider. Tiny, because orders leave this set as soon as a rider accepts.
create index orders_open_offers_idx on public.orders (created_at)
  where rider_id is null and status in ('accepted', 'preparing', 'ready');

create trigger orders_set_updated_at
  before update on public.orders
  for each row execute function private.set_updated_at();

-- ---------------------------------------------------------------------------------------------
-- order_items: what was ordered, priced at the moment of ordering.
-- ---------------------------------------------------------------------------------------------
create table public.order_items (
  id bigint generated always as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  -- SET NULL: if the store later deletes the product, the order line (with its name) remains.
  product_id bigint references public.products (id) on delete set null,
  product_name text not null,
  unit_price numeric(12, 2) not null check (unit_price >= 0),
  quantity integer not null check (quantity > 0),
  line_total numeric(12, 2) generated always as (unit_price * quantity) stored,
  created_at timestamptz not null default now()
);

comment on table public.order_items is 'Lines of an order, with the name and price as they were when ordered.';

create index order_items_order_id_idx on public.order_items (order_id);
create index order_items_product_id_idx on public.order_items (product_id) where product_id is not null;

-- ---------------------------------------------------------------------------------------------
-- order_events: append-only history, shown as the order timeline.
-- ---------------------------------------------------------------------------------------------
create table public.order_events (
  id bigint generated always as identity primary key,
  order_id bigint not null references public.orders (id) on delete cascade,
  event_type public.order_event_type not null,
  -- The order's status after this event.
  status public.order_status not null,
  actor_id uuid references public.profiles (id) on delete set null,
  note text check (char_length(note) <= 500),
  created_at timestamptz not null default now()
);

comment on table public.order_events is 'Append-only timeline of what happened to an order and who did it.';

create index order_events_order_created_idx on public.order_events (order_id, created_at);
-- Lets a profile be removed without scanning every event ("who did this" is set to null).
create index order_events_actor_id_idx on public.order_events (actor_id) where actor_id is not null;

-- ---------------------------------------------------------------------------------------------
-- Access rules: read-only, and only for the people involved in the order.
-- ---------------------------------------------------------------------------------------------
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.order_events enable row level security;

revoke all on table public.orders, public.order_items, public.order_events from anon, authenticated;
grant select on public.orders, public.order_items, public.order_events to authenticated;
grant all on public.orders, public.order_items, public.order_events to service_role;

create policy orders_select_customer on public.orders
  for select to authenticated
  using (customer_id = (select auth.uid()));

create policy orders_select_store_owner on public.orders
  for select to authenticated
  using (exists (
    select 1 from public.stores s
    where s.id = orders.store_id and s.owner_id = (select auth.uid())
  ));

-- A rider sees an order only after accepting it. Before that they get a limited preview from
-- list_delivery_offers(), which never includes the customer's name, phone or exact address.
create policy orders_select_rider on public.orders
  for select to authenticated
  using (rider_id = (select auth.uid()));

-- Items and events follow the order: if you can see the order, you can see its items and events.
create policy order_items_select_via_order on public.order_items
  for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_items.order_id));

create policy order_events_select_via_order on public.order_events
  for select to authenticated
  using (exists (select 1 from public.orders o where o.id = order_events.order_id));

-- ---------------------------------------------------------------------------------------------
-- Let the people on an active order see the rider assigned to it (name, phone, status).
-- `exists (... from orders ...)` runs under the orders policies above, so it is true only when the
-- caller is the customer, the store owner or the rider on that order. The access ends when the
-- order does.
-- ---------------------------------------------------------------------------------------------
create policy profiles_select_order_rider on public.profiles
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.rider_id = profiles.id
      and o.status in ('accepted', 'preparing', 'ready', 'picked_up')
  ));

create policy riders_select_order_rider on public.riders
  for select to authenticated
  using (exists (
    select 1 from public.orders o
    where o.rider_id = riders.user_id
      and o.status in ('accepted', 'preparing', 'ready', 'picked_up')
  ));

-- Push order changes to the app in real time (customer tracking, store and rider screens).
-- Row-level security still decides who receives which change. The publication exists on Supabase;
-- the guard just keeps this file runnable elsewhere.
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime') then
    alter publication supabase_realtime add table public.orders;
  end if;
end;
$$;
